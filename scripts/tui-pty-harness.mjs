#!/usr/bin/env node
/**
 * PTY-driven TUI harness for pi-zig interactive mode.
 *
 * Uses expect(1) (available on macOS/Linux) to allocate a real PTY, launch
 * pi-zig in interactive mode, and drive a deterministic interaction sequence.
 * Written to test/fixtures/tui-transcript.txt for artifact inspection.
 *
 * Scenarios exercised:
 *   1. Full prompt lifecycle: banner → /session info → /hotkeys → /quit
 *   2. Abort path: /new → user text typed but Ctrl+C clears the editor (no provider needed)
 *
 * Run independently (not included in npm run test because it needs a real TTY):
 *   node scripts/tui-pty-harness.mjs
 *
 * With a fake provider:
 *   PI_ZIG_BIN=zig-out/bin/pi-zig \
 *   PI_ZIG_PROVIDER=openai \
 *   PI_ZIG_PROVIDER_BASE_URL=http://127.0.0.1:3099/v1 \
 *   OPENAI_API_KEY=fake \
 *   node scripts/tui-pty-harness.mjs
 */

import { execFileSync, spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const here = fileURLToPath(new URL('.', import.meta.url));
const repoRoot = resolve(here, '..');
const binary = process.env.PI_ZIG_BIN ?? resolve(repoRoot, 'zig-out/bin/pi-zig');
const transcriptDir = resolve(repoRoot, 'test/fixtures');
const transcriptFile = resolve(transcriptDir, 'tui-transcript.txt');

mkdirSync(transcriptDir, { recursive: true });

// Build provider args if configured.
const providerArgs = [];
if (process.env.PI_ZIG_PROVIDER) providerArgs.push('--provider', process.env.PI_ZIG_PROVIDER);
if (process.env.PI_ZIG_MODEL) providerArgs.push('--model', process.env.PI_ZIG_MODEL);

// Escape for use inside expect(1) double-quoted strings.
function expEsc(s) {
  return s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\[/g, '\\[').replace(/\]/g, '\\]');
}

const spawnCmd = [binary, ...providerArgs].map(expEsc).join(' ');
const transcriptPath = transcriptFile.replace(/\\/g, '\\\\');

const expectScript = `#!/usr/bin/expect -f
# pi-zig TUI PTY harness
# Generated by scripts/tui-pty-harness.mjs

set timeout 8
log_file -noappend "${transcriptPath}"

# -- Scenario 1: Full prompt lifecycle --
spawn ${spawnCmd}

# Verify banner
expect {
    "interactive mode" { }
    timeout { puts stderr "FAIL scenario1: banner not shown within timeout"; exit 1 }
    eof     { puts stderr "FAIL scenario1: process exited before banner"; exit 1 }
}

# /session command shows session info
send "/session\\r"
expect {
    "Session:" { }
    timeout { puts stderr "FAIL scenario1: /session output not shown"; exit 2 }
    eof     { puts stderr "FAIL scenario1: process exited"; exit 2 }
}

# /hotkeys shows keyboard shortcuts
send "/hotkeys\\r"
expect {
    "Keyboard shortcuts:" { }
    timeout { puts stderr "FAIL scenario1: /hotkeys output not shown"; exit 3 }
    eof     { puts stderr "FAIL scenario1: process exited"; exit 3 }
}

# -- Scenario 2: Abort path (editor clear) --
# Type some text, then Ctrl+C to clear it without sending
send "hello world"
after 200
# Ctrl+C clears the editor in idle mode (not abort, just clear)
send "\\x03"
after 100

# /new clears the transcript
send "/new\\r"
expect {
    "new session" { }
    timeout { puts stderr "FAIL scenario2: /new output not shown"; exit 4 }
    eof     { puts stderr "FAIL scenario2: process exited"; exit 4 }
}

# Clean quit
send "/quit\\r"
expect {
    eof { }
    timeout { puts stderr "FAIL: /quit did not exit within timeout"; exit 5 }
}

puts "PASS: TUI PTY harness scenarios 1-2 complete"
`;

const scriptPath = '/tmp/pi-zig-tui-harness.exp';
writeFileSync(scriptPath, expectScript, { mode: 0o755 });

// Check if expect(1) is available.
const expectCheck = spawnSync('which', ['expect'], { encoding: 'utf8' });
if (expectCheck.status !== 0) {
  console.log('[tui-pty-harness] SKIP: expect(1) not found on PATH');
  console.log('[tui-pty-harness] Install expect and re-run, or run manually:');
  console.log(`  expect ${scriptPath}`);
  process.exit(0);
}

// Check binary exists.
const binCheck = spawnSync('test', ['-f', binary]);
if (binCheck.status !== 0) {
  console.error(`[tui-pty-harness] SKIP: binary not found: ${binary}`);
  console.error('[tui-pty-harness] Run "zig build" first.');
  process.exit(0);
}

try {
  execFileSync('expect', [scriptPath], {
    stdio: 'inherit',
    timeout: 20_000,
    env: { ...process.env },
  });
  console.log(`[tui-pty-harness] PASS — transcript: ${transcriptFile}`);
} catch (err) {
  if (err.code === 'ENOENT') {
    console.log('[tui-pty-harness] SKIP: expect not executable');
    process.exit(0);
  }
  process.stderr.write(`[tui-pty-harness] FAIL: exit=${err.status ?? '?'}\n`);
  process.exit(err.status ?? 1);
}
