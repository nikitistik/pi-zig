import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import vm from 'node:vm';

const upstreamFile = path.resolve('upstream/pi/packages/ai/src/models.generated.ts');
const outputFile = path.resolve('src/pi/models.generated.zig');
const checkOnly = process.argv.includes('--check');

function loadModels() {
  let source = fs.readFileSync(upstreamFile, 'utf8');
  source = source
    .replace(/^import[^\n]*\n/gm, '')
    .replace(/export const MODELS =/, 'const MODELS =')
    .replace(/ satisfies Model<[^>]+>/g, '')
    .replace(/}\s+as const;\s*$/, '}; globalThis.MODELS = MODELS;');
  const context = {};
  vm.runInNewContext(source, context, { filename: upstreamFile });
  return context.MODELS;
}

function zigString(value) {
  const bytes = Buffer.from(String(value ?? ''), 'utf8');
  let out = '"';
  for (const byte of bytes) {
    if (byte === 0x22) out += '\\"';
    else if (byte === 0x5c) out += '\\\\';
    else if (byte === 0x0a) out += '\\n';
    else if (byte === 0x0d) out += '\\r';
    else if (byte === 0x09) out += '\\t';
    else if (byte >= 0x20 && byte <= 0x7e) out += String.fromCharCode(byte);
    else out += `\\x${byte.toString(16).padStart(2, '0')}`;
  }
  out += '"';
  return out;
}

function zigFloat(value) {
  const number = Number(value ?? 0);
  if (!Number.isFinite(number)) return '0';
  return String(number);
}

function hasInput(model, kind) {
  return Array.isArray(model.input) && model.input.includes(kind);
}

function thinkingDisabled(model, level) {
  return model.thinkingLevelMap?.[level] === null;
}

function xhighSupported(model) {
  return model.thinkingLevelMap?.xhigh !== undefined && model.thinkingLevelMap?.xhigh !== null;
}

function generate() {
  const modelsByProvider = loadModels();
  const providers = Object.keys(modelsByProvider).sort();
  const rows = [];
  for (const provider of providers) {
    for (const model of Object.values(modelsByProvider[provider])) {
      rows.push(model);
    }
  }

  const lines = [];
  lines.push('// Generated by scripts/generate-model-catalog.mjs from upstream/pi/packages/ai/src/models.generated.ts.');
  lines.push('// Do not edit by hand.');
  lines.push('');
  lines.push('pub const ModelEntry = struct {');
  lines.push('    provider: []const u8,');
  lines.push('    id: []const u8,');
  lines.push('    name: []const u8,');
  lines.push('    api: []const u8,');
  lines.push('    base_url: []const u8,');
  lines.push('    reasoning: bool,');
  lines.push('    input_text: bool,');
  lines.push('    input_image: bool,');
  lines.push('    cost_input: f64,');
  lines.push('    cost_output: f64,');
  lines.push('    cost_cache_read: f64,');
  lines.push('    cost_cache_write: f64,');
  lines.push('    context_window: usize,');
  lines.push('    max_tokens: usize,');
  lines.push('    thinking_off_disabled: bool,');
  lines.push('    thinking_minimal_disabled: bool,');
  lines.push('    thinking_low_disabled: bool,');
  lines.push('    thinking_medium_disabled: bool,');
  lines.push('    thinking_high_disabled: bool,');
  lines.push('    thinking_xhigh_supported: bool,');
  lines.push('};');
  lines.push('');
  lines.push(`pub const upstream_model_count: usize = ${rows.length};`);
  lines.push(`pub const upstream_provider_count: usize = ${providers.length};`);
  lines.push('');
  lines.push('pub const provider_names = [_][]const u8{');
  for (const provider of providers) {
    lines.push(`    ${zigString(provider)},`);
  }
  lines.push('};');
  lines.push('');
  lines.push('pub const models = [_]ModelEntry{');
  for (const model of rows) {
    lines.push('    .{');
    lines.push(`        .provider = ${zigString(model.provider)},`);
    lines.push(`        .id = ${zigString(model.id)},`);
    lines.push(`        .name = ${zigString(model.name ?? model.id)},`);
    lines.push(`        .api = ${zigString(model.api ?? '')},`);
    lines.push(`        .base_url = ${zigString(model.baseUrl ?? '')},`);
    lines.push(`        .reasoning = ${model.reasoning ? 'true' : 'false'},`);
    lines.push(`        .input_text = ${hasInput(model, 'text') ? 'true' : 'false'},`);
    lines.push(`        .input_image = ${hasInput(model, 'image') ? 'true' : 'false'},`);
    lines.push(`        .cost_input = ${zigFloat(model.cost?.input)},`);
    lines.push(`        .cost_output = ${zigFloat(model.cost?.output)},`);
    lines.push(`        .cost_cache_read = ${zigFloat(model.cost?.cacheRead)},`);
    lines.push(`        .cost_cache_write = ${zigFloat(model.cost?.cacheWrite)},`);
    lines.push(`        .context_window = ${Number(model.contextWindow ?? 0)},`);
    lines.push(`        .max_tokens = ${Number(model.maxTokens ?? 0)},`);
    lines.push(`        .thinking_off_disabled = ${thinkingDisabled(model, 'off') ? 'true' : 'false'},`);
    lines.push(`        .thinking_minimal_disabled = ${thinkingDisabled(model, 'minimal') ? 'true' : 'false'},`);
    lines.push(`        .thinking_low_disabled = ${thinkingDisabled(model, 'low') ? 'true' : 'false'},`);
    lines.push(`        .thinking_medium_disabled = ${thinkingDisabled(model, 'medium') ? 'true' : 'false'},`);
    lines.push(`        .thinking_high_disabled = ${thinkingDisabled(model, 'high') ? 'true' : 'false'},`);
    lines.push(`        .thinking_xhigh_supported = ${xhighSupported(model) ? 'true' : 'false'},`);
    lines.push('    },');
  }
  lines.push('};');
  lines.push('');
  return `${lines.join('\n')}\n`;
}

const generated = generate();

function formatZigFile(file) {
  const result = spawnSync('zig', ['fmt', file], { encoding: 'utf8' });
  if (result.status !== 0) {
    throw new Error(`zig fmt failed for ${file}: ${result.stderr || result.stdout}`);
  }
}

function formattedGeneratedSource(source) {
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'pi-zig-models-'));
  const tmpFile = path.join(tmpDir, 'models.generated.zig');
  try {
    fs.writeFileSync(tmpFile, source);
    formatZigFile(tmpFile);
    return fs.readFileSync(tmpFile, 'utf8');
  } finally {
    fs.rmSync(tmpDir, { recursive: true, force: true });
  }
}

if (checkOnly) {
  const formatted = formattedGeneratedSource(generated);
  const current = fs.existsSync(outputFile) ? fs.readFileSync(outputFile, 'utf8') : '';
  if (current !== formatted) {
    throw new Error('src/pi/models.generated.zig is out of date; run node scripts/generate-model-catalog.mjs');
  }
  console.log('model catalog generated file is current');
} else {
  fs.writeFileSync(outputFile, generated);
  formatZigFile(outputFile);
  console.log(`wrote ${path.relative(process.cwd(), outputFile)}`);
}
